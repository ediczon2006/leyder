-- 1. Tabla de Clientes
CREATE TABLE IF NOT EXISTS public.clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  dni VARCHAR(20),
  celular VARCHAR(30),
  fecha_inicio DATE,
  ip VARCHAR(50),
  direccion TEXT,
  zona VARCHAR(100),
  plan NUMERIC DEFAULT 65,
  cable NUMERIC DEFAULT 0,
  estado VARCHAR(30) DEFAULT 'ACTIVO',
  notas TEXT,
  obs TEXT,
  creado_el TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabla de Pagos
CREATE TABLE IF NOT EXISTS public.pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente BIGINT REFERENCES public.clientes(id) ON DELETE CASCADE,
  cliente_nombre TEXT,
  cliente_zona TEXT,
  monto NUMERIC NOT NULL DEFAULT 65,
  fecha DATE DEFAULT CURRENT_DATE,
  mes VARCHAR(50),
  metodo VARCHAR(50) DEFAULT 'Efectivo',
  numero_operacion VARCHAR(100),
  codigo_operacion VARCHAR(100),
  notas TEXT,
  obs TEXT,
  creado_el TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla de Cortes
CREATE TABLE IF NOT EXISTS public.cortes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente BIGINT REFERENCES public.clientes(id) ON DELETE CASCADE,
  cliente_nombre TEXT,
  zona VARCHAR(100),
  fecha_corte DATE DEFAULT CURRENT_DATE,
  fecha_reconexion DATE,
  fecha_reconex TIMESTAMPTZ,
  motivo TEXT,
  estado VARCHAR(30) DEFAULT 'CORTADO',
  costo_reconeccion NUMERIC DEFAULT 0,
  notas TEXT,
  creado_el TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabla de Fotos y Archivos ISP
CREATE TABLE IF NOT EXISTS public.fotos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT,
  nombre TEXT,
  categoria VARCHAR(50) DEFAULT 'comprobante',
  cliente_id BIGINT,
  cliente_nombre TEXT,
  zona VARCHAR(100),
  tamano BIGINT,
  tipo_mime VARCHAR(100),
  data_url TEXT,
  url_data TEXT,
  url TEXT,
  notas TEXT,
  mtime TIMESTAMPTZ DEFAULT NOW(),
  creado_el TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Habilitar RLS (Row Level Security) y Políticas de Acceso Público
ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pagos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cortes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fotos ENABLE ROW LEVEL SECURITY;

-- Políticas para acceso anónimo (Permitir lectura, inserción, actualización y borrado)
DROP POLICY IF EXISTS "Acceso total clientes" ON public.clientes;
CREATE POLICY "Acceso total clientes" ON public.clientes FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total pagos" ON public.pagos;
CREATE POLICY "Acceso total pagos" ON public.pagos FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total cortes" ON public.cortes;
CREATE POLICY "Acceso total cortes" ON public.cortes FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso total fotos" ON public.fotos;
CREATE POLICY "Acceso total fotos" ON public.fotos FOR ALL USING (true) WITH CHECK (true);

-- Índices optimizados para velocidad en búsquedas
CREATE INDEX IF NOT EXISTS idx_clientes_zona_estado ON public.clientes(zona, estado);
CREATE INDEX IF NOT EXISTS idx_clientes_ip ON public.clientes(ip);
CREATE INDEX IF NOT EXISTS idx_clientes_nombre ON public.clientes(nombre);
CREATE INDEX IF NOT EXISTS idx_pagos_mes ON public.pagos(mes);
CREATE INDEX IF NOT EXISTS idx_pagos_cliente ON public.pagos(id_cliente);
CREATE INDEX IF NOT EXISTS idx_cortes_cliente ON public.cortes(id_cliente);
CREATE INDEX IF NOT EXISTS idx_fotos_categoria ON public.fotos(categoria);
CREATE INDEX IF NOT EXISTS idx_fotos_cliente ON public.fotos(cliente_id);
