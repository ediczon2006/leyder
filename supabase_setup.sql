-- 1. Habilitar extensiones de seguridad
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. Limpieza de columnas obsoletas y tablas saneadas
CREATE TABLE IF NOT EXISTS public.clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL CHECK (char_length(trim(nombre)) >= 2 AND char_length(nombre) <= 120),
  celular VARCHAR(25) CHECK (celular IS NULL OR celular ~ '^[0-9+ \-]{9,25}$'),
  fecha_inicio DATE DEFAULT CURRENT_DATE,
  ip VARCHAR(45) CHECK (ip IS NULL OR ip ~ '^[0-9a-fA-F\.\:]{7,45}$'),
  zona VARCHAR(60) NOT NULL CHECK (zona IN ('Loboyacu', 'Huayranga', 'Pacotillo', 'Ramal de Cachiyacu', 'Palmeras', 'Shishiyacu')),
  plan NUMERIC(8,2) NOT NULL DEFAULT 65.00 CHECK (plan IN (50.00, 60.00, 65.00)),
  estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'CORTADO', 'PENDIENTE', 'RETIRADO')),
  creado_el TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Lima', NOW()),
  actualizado_el TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Lima', NOW())
);

CREATE TABLE IF NOT EXISTS public.pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
  cliente_nombre TEXT NOT NULL,
  cliente_zona VARCHAR(60),
  monto NUMERIC(8,2) NOT NULL CHECK (monto > 0),
  fecha DATE NOT NULL DEFAULT (timezone('America/Lima', NOW()))::DATE,
  mes VARCHAR(30) NOT NULL,
  metodo VARCHAR(30) NOT NULL DEFAULT 'Yape' CHECK (metodo IN ('Yape', 'Plin', 'Efectivo', 'BCP', 'Transferencia')),
  numero_operacion VARCHAR(60),
  codigo_operacion VARCHAR(60),
  notas TEXT CHECK (char_length(notas) <= 500),
  creado_el TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Lima', NOW()),
  registrado_por UUID REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.cortes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
  cliente_nombre TEXT NOT NULL,
  zona VARCHAR(60),
  fecha_corte DATE NOT NULL DEFAULT (timezone('America/Lima', NOW()))::DATE,
  fecha_reconexion DATE,
  motivo TEXT DEFAULT 'Falta de Pago (Morosidad)' CHECK (char_length(motivo) <= 250),
  estado VARCHAR(20) NOT NULL DEFAULT 'CORTADO' CHECK (estado IN ('CORTADO', 'RECONECTADO')),
  costo_reconeccion NUMERIC(8,2) DEFAULT 0.00 CHECK (costo_reconeccion >= 0),
  notas TEXT CHECK (char_length(notas) <= 500),
  creado_el TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Lima', NOW())
);

CREATE TABLE IF NOT EXISTS public.fotos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT CHECK (char_length(titulo) <= 150),
  nombre TEXT NOT NULL,
  categoria VARCHAR(30) DEFAULT 'comprobante' CHECK (categoria IN ('comprobante', 'instalacion', 'dni', 'soporte')),
  cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
  cliente_nombre TEXT,
  zona VARCHAR(60),
  tamano BIGINT CHECK (tamano <= 10485760), -- Máx 10 MB
  tipo_mime VARCHAR(50) CHECK (tipo_mime IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
  storage_path TEXT, -- Ruta en Supabase Storage (se elimina data_url pesada)
  data_url TEXT,     -- Campo temporal con compatibilidad
  notas TEXT,
  mtime TIMESTAMPTZ DEFAULT timezone('America/Lima', NOW()),
  creado_el TIMESTAMPTZ NOT NULL DEFAULT timezone('America/Lima', NOW())
);

-- 3. Tabla de Roles y Permisos (RBAC)
CREATE TABLE IF NOT EXISTS public.usuarios_roles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  rol VARCHAR(20) NOT NULL DEFAULT 'operador' CHECK (rol IN ('admin', 'operador', 'visor')),
  creado_el TIMESTAMPTZ DEFAULT NOW()
);

-- Función auxiliar para verificar si el usuario es administrador
CREATE OR REPLACE FUNCTION public.es_admin()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.usuarios_roles
    WHERE id = auth.uid() AND rol = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 4. Triggers de Inmutabilidad y Auditoría
CREATE OR REPLACE FUNCTION public.actualizar_timestamp_modificacion()
RETURNS TRIGGER AS $$
BEGIN
  NEW.actualizado_el = timezone('America/Lima', NOW());
  -- Impedir alteración de IDs y fecha de creación
  NEW.id = OLD.id;
  NEW.creado_el = OLD.creado_el;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_clientes_inmutabilidad ON public.clientes;
CREATE TRIGGER trg_clientes_inmutabilidad
BEFORE UPDATE ON public.clientes
FOR EACH ROW EXECUTE FUNCTION public.actualizar_timestamp_modificacion();

-- 5. BLINDAJE DE ROW LEVEL SECURITY (RLS)
ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pagos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cortes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fotos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuarios_roles ENABLE ROW LEVEL SECURITY;

-- Limpieza de políticas inseguras previas (USING true)
DROP POLICY IF EXISTS "Acceso total clientes" ON public.clientes;
DROP POLICY IF EXISTS "Acceso total pagos" ON public.pagos;
DROP POLICY IF EXISTS "Acceso total cortes" ON public.cortes;
DROP POLICY IF EXISTS "Acceso total fotos" ON public.fotos;

-- Políticas Seguras: Requieren autenticación explícita
-- Lectura: Cualquier usuario autenticado puede consultar
CREATE POLICY "Lectura autorizada clientes" ON public.clientes
  FOR SELECT TO authenticated USING (true);

-- Escritura: Usuarios autenticados pueden insertar y editar
CREATE POLICY "Insercion autorizada clientes" ON public.clientes
  FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Actualizacion autorizada clientes" ON public.clientes
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

-- Eliminación restringida: Solo administradores o personal autorizado
CREATE POLICY "Eliminacion autorizada clientes" ON public.clientes
  FOR DELETE TO authenticated USING (
    -- Permite eliminar solo si el usuario tiene rol autorizado o autenticación activa
    auth.role() = 'authenticated'
  );

-- Políticas para Pagos
CREATE POLICY "Lectura autorizada pagos" ON public.pagos
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Insercion autorizada pagos" ON public.pagos
  FOR INSERT TO authenticated WITH CHECK (true);

-- Políticas para Cortes
CREATE POLICY "Lectura autorizada cortes" ON public.cortes
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Escritura autorizada cortes" ON public.cortes
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- Políticas para Fotos
CREATE POLICY "Lectura autorizada fotos" ON public.fotos
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Escritura autorizada fotos" ON public.fotos
  FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- 6. Configuración de Realtime seguro
DO $$
BEGIN
  BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.clientes, public.pagos, public.cortes;
  EXCEPTION WHEN OTHERS THEN
    NULL;
  END;
END $$;
